"""Rebuild kernel/kernel.py with the current UI + gateway + auth embedded.

Usage (from anywhere):
    python "E:\\Side Projects\\qwen-kaggle\\gateway\\build.py"
Then deploy:
    kaggle kernels push -p "E:\\Side Projects\\qwen-kaggle\\kernel"

Why embedding: a Kaggle script kernel is a single .py file. Rather than depending on a
separate Kaggle dataset for the UI, the HTML/gateway/auth are base64-embedded into the
kernel source, so one `push` deploys everything atomically.
"""
import base64, io, json, ast, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = {
    'html': os.path.join(ROOT, 'app', 'chat.html'),
    'gw':   os.path.join(HERE, 'gateway.py'),
    'auth': os.path.join(HERE, 'auth.json'),
    'tpl':  os.path.join(HERE, 'kernel_template.py'),
}
DEST = os.path.join(ROOT, 'kernel', 'kernel.py')

for name, path in SRC.items():
    if not os.path.exists(path):
        raise SystemExit(f'missing source file: {path}')

html = open(SRC['html'], 'rb').read()
gw = open(SRC['gw'], 'rb').read()
auth = open(SRC['auth'], 'rb').read()
tpl = io.open(SRC['tpl'], encoding='utf-8').read()

user = json.loads(auth)['user']
header = (
    "# AUTO-GENERATED by gateway/build.py - DO NOT EDIT THIS FILE.\n"
    "# Edit app/chat.html, gateway/gateway.py or gateway/kernel_template.py, then rebuild.\n"
    f"HTML_B64 = '{base64.b64encode(html).decode()}'\n"
    f"GATEWAY_B64 = '{base64.b64encode(gw).decode()}'\n"
    f"AUTH_B64 = '{base64.b64encode(auth).decode()}'\n"
    f"USERNAME = {user!r}\n\n"
)
out = header + tpl
ast.parse(out)                      # fail loudly here rather than on Kaggle
io.open(DEST, 'w', encoding='utf-8', newline='\n').write(out)

print(f'wrote {DEST}')
print(f'  {len(out):,} bytes total  (html {len(html):,} | gateway {len(gw):,})  - syntax OK')
print(f'\nnow deploy:  kaggle kernels push -p "{os.path.join(ROOT, "kernel")}"')
