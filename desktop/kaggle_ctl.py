"""Kaggle control for the Qwen app (in-process, no kaggle CLI): build + push (start), delete (hard stop), status and GPU quota."""
import io, os, shutil, subprocess, sys, tempfile

HERE = os.environ.get("QWEN_APP_HOME") or os.path.dirname(os.path.abspath(__file__))   # the desktop/ folder
PROJECT = os.path.dirname(HERE)                      # the "Qwen 3.8 27b - kaggle" folder
AUTH_FILE = os.path.join(PROJECT, "gateway", "auth.json")
KAGGLE_JSON = os.path.join(os.path.expanduser("~"), ".kaggle", "kaggle.json")


def _creds():
    """(username, key) from ~/.kaggle/kaggle.json. key is either a KGAT_ access token or a legacy API key."""
    import json as _json
    try:
        j = _json.load(open(KAGGLE_JSON, encoding="utf-8"))
        return j.get("username", ""), j.get("key", "")
    except Exception:
        return "", ""


def _auth():
    import json as _json
    try:
        return _json.load(open(AUTH_FILE, encoding="utf-8"))
    except Exception:
        return {}


def configure_env():
    _user, _key = _creds()
    for k in ("KAGGLE_API_TOKEN", "KAGGLE_USERNAME", "KAGGLE_KEY"):
        os.environ.pop(k, None)
    if _key.startswith("KGAT_"):
        os.environ["KAGGLE_API_TOKEN"] = _key
    elif _user and _key:
        os.environ["KAGGLE_USERNAME"], os.environ["KAGGLE_KEY"] = _user, _key


configure_env()
os.environ.setdefault("KAGGLE_CONFIG_DIR", os.path.join(HERE, ".kaggle_cfg"))
os.makedirs(os.environ["KAGGLE_CONFIG_DIR"], exist_ok=True)

from kaggle.api.kaggle_api_extended import KaggleApi  # noqa: E402


def kernel_id():
    a = _auth()
    user = a.get("kaggle_user") or a.get("user") or _creds()[0]
    return f"{user}/{a.get('kernel_slug') or 'qwen-3-8-27b-uncensered'}"


_api = None


def reset():
    """Forget the cached client (after new credentials were saved)."""
    global _api
    _api = None
    configure_env()


def api():
    global _api
    if _api is None:
        _api = KaggleApi()
        _api.authenticate()
    return _api


def build_kernel():
    """Rebuild kernel/kernel.py from app/chat.html + gateway/*.py + auth.json (same as gateway/build.py)."""
    import ast, base64, json
    gw_dir = os.path.join(PROJECT, "gateway")
    html = open(os.path.join(PROJECT, "app", "chat.html"), "rb").read()
    gw = open(os.path.join(gw_dir, "gateway.py"), "rb").read()
    auth = open(os.path.join(gw_dir, "auth.json"), "rb").read()
    tpl = io.open(os.path.join(gw_dir, "kernel_template.py"), encoding="utf-8").read()
    user = json.loads(auth)["user"]
    out = ("# AUTO-GENERATED by gateway/build.py - DO NOT EDIT THIS FILE.\n"
           "# Edit app/chat.html, gateway/gateway.py or gateway/kernel_template.py, then rebuild.\n"
           f"HTML_B64 = '{base64.b64encode(html).decode()}'\n"
           f"GATEWAY_B64 = '{base64.b64encode(gw).decode()}'\n"
           f"AUTH_B64 = '{base64.b64encode(auth).decode()}'\n"
           f"USERNAME = {user!r}\n\n") + tpl
    ast.parse(out)
    dest = os.path.join(PROJECT, "kernel", "kernel.py")
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    io.open(dest, "w", encoding="utf-8", newline="\n").write(out)
    return dest


def push():
    import json
    src = build_kernel()
    d = tempfile.mkdtemp()
    try:
        shutil.copy(src, os.path.join(d, "kernel.py"))
        kid = kernel_id()
        json.dump({"id": kid, "title": kid.split("/", 1)[1], "code_file": "kernel.py", "language": "python",
                   "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
                   "machine_shape": "NvidiaTeslaT4", "dataset_sources": [], "competition_sources": [],
                   "kernel_sources": []}, open(os.path.join(d, "kernel-metadata.json"), "w"))
        r = api().kernels_push(d)
        if getattr(r, "error", None):
            raise RuntimeError(r.error)
        return {"version": r.version_number, "url": r.url}
    finally:
        shutil.rmtree(d, ignore_errors=True)


def status():
    """'running', 'queued', 'complete', 'error', 'cancel...', or 'none' if the kernel doesn't exist."""
    try:
        r = api().kernels_status(kernel_id())
        s = str(getattr(r, "status", r)).lower()
        return s.split(".")[-1]
    except Exception as e:
        if any(s in str(e).lower() for s in ("404", "not found", "denied", "403")):
            return "none"
        raise


def delete():
    try:
        api().kernels_delete(kernel_id(), no_confirm=True)
        return True
    except Exception as e:
        if any(s in str(e).lower() for s in ("404", "not found", "denied", "403")):
            return False
        raise


def quota():
    from kagglesdk.kernels.types.kernels_api_service import ApiGetAcceleratorQuotaStatisticsRequest
    with api().build_kaggle_client() as k:
        r = k.kernels.kernels_api_client.get_accelerator_quota_statistics(ApiGetAcceleratorQuotaStatisticsRequest())
    q = r.gpu_quota
    h = lambda td: round(td.total_seconds() / 3600, 2) if td else 0.0
    return {"used_h": h(q.time_used), "reserved_h": h(q.time_reserved), "total_h": h(q.total_time_allowed),
            "refresh": r.quota_refresh_time.isoformat() if r.quota_refresh_time else None}


OAUTH_FILE = os.path.join(os.path.expanduser("~"), ".kaggle", "credentials.json")


def oauth_user():
    """Username of a 'Sign in with Kaggle' login saved on this PC, or ''."""
    import json as _json
    try:
        return _json.load(open(OAUTH_FILE, encoding="utf-8")).get("username", "")
    except Exception:
        return ""


_oauth = {}


def oauth_login():
    """Opens Kaggle's sign-in page in the browser; returns the username once the user clicks Allow.
    The refresh token lands in ~/.kaggle/credentials.json, which the Kaggle API then uses by itself."""
    from kagglesdk.kaggle_oauth import KaggleOAuth
    old = _oauth.get("flow")
    if old:
        try:
            old.stop_server()
        except Exception:
            pass
    reset()
    a = KaggleApi()
    with a.build_kaggle_client() as k:
        flow = KaggleOAuth(client=k)
        _oauth["flow"] = flow
        creds = flow.authenticate(scopes=["resources.admin:*"])
    reset()
    return creds.get_username()


def check():
    """True if the saved Kaggle credentials work (lists the user's own kernels)."""
    user = _creds()[0] or _auth().get("kaggle_user", "")
    api().kernels_list(user=user or None, mine=not user, page_size=1)
    return True


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "status"
    print({"status": status, "quota": quota, "delete": delete, "push": push, "build": build_kernel, "check": check, "id": kernel_id}[cmd]())
